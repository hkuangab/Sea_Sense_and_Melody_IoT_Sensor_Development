def build_sequences(df: pd.DataFrame, window_size: int, stride: int = 1) -> tuple:
    """
    Build sliding window sequences from flat time series.
    
    Converts a DataFrame of sequential observations into overlapping windows.
    Each window becomes one training sample. Label is determined by the
    emotion at the LAST frame of the window (most recent state).
    
    Args:
        df: Input DataFrame with features and labels
        window_size: Number of time steps per sequence
        stride: Step size between consecutive windows
    
    Returns:
        X_seq: Array of shape (num_sequences, window_size, num_features)
        y_seq: Array of shape (num_sequences,) with labels
    """
    features = df[CONFIG['feature_cols']].values
    labels = df[CONFIG['label_col']].values
    
    X_seq, y_seq = [], []
    for start in range(0, len(features) - window_size + 1, stride):
        end = start + window_size
        X_seq.append(features[start:end])
        # Label = emotion at the LAST frame of the window
        y_seq.append(labels[end - 1])
    
    return np.array(X_seq), np.array(y_seq)


def plot_training_curves(train_losses: list, val_losses: list,
                         train_accs: list, val_accs: list,
                         save_path: str):
    """
    Plot and save training/validation loss and accuracy curves.
    
    Creates a 2x2 figure with annotations for best values.
    
    Args:
        train_losses: List of training loss values per epoch
        val_losses: List of validation loss values per epoch
        train_accs: List of training accuracy values per epoch
        val_accs: List of validation accuracy values per epoch
        save_path: File path to save the PNG image
    """
    epochs = range(1, len(train_losses) + 1)
    
    fig, axes = plt.subplots(1, 2, figsize=(16, 6))
    
    # Left: Loss Curves
    ax1 = axes[0]
    ax1.plot(epochs, train_losses, 'b-', linewidth=2, label='Training Loss', alpha=0.8)
    ax1.plot(epochs, val_losses, 'r-', linewidth=2, label='Validation Loss', alpha=0.8)
    ax1.set_xlabel('Epoch')
    ax1.set_ylabel('Loss')
    ax1.set_title('Loss Curves')
    ax1.grid(True, alpha=0.3)
    ax1.legend()
    
    min_val_loss = min(val_losses)
    min_epoch = val_losses.index(min_val_loss) + 1
    ax1.annotate(f'Min Val: {min_val_loss:.4f} @ Epoch {min_epoch}',
                xy=(min_epoch, min_val_loss),
                xytext=(min_epoch + 10, min_val_loss + 0.2),
                arrowprops=dict(arrowstyle='->', color='darkred'),
                fontsize=9)
    
    # Right: Accuracy Curves
    ax2 = axes[1]
    ax2.plot(epochs, train_accs, 'b-', linewidth=2, label='Training Acc', alpha=0.8)
    ax2.plot(epochs, val_accs, 'r-', linewidth=2, label='Validation Acc', alpha=0.8)
    ax2.set_xlabel('Epoch')
    ax2.set_ylabel('Accuracy')
    ax2.set_title('Accuracy Curves')
    ax2.grid(True, alpha=0.3)
    ax2.legend()
    ax2.set_ylim(0, 1.0)
    
    max_val_acc = max(val_accs)
    max_epoch = val_accs.index(max_val_acc) + 1
    ax2.annotate(f'Max Val: {max_val_acc:.4f} @ Epoch {max_epoch}',
                xy=(max_epoch, max_val_acc),
                xytext=(max_epoch + 10, max_val_acc - 0.15),
                arrowprops=dict(arrowstyle='->', color='darkgreen'),
                fontsize=9)
    
    # Add chance level line
    chance = 1.0 / NUM_CLASSES
    ax2.axhline(y=chance, color='gray', linestyle='--', alpha=0.5,
                label=f'Chance ({chance:.2f})')
    ax2.legend()
    
    plt.suptitle(f'GRU Emotion Classifier Training ({NUM_CLASSES} classes)',
                 fontsize=14, fontweight='bold')
    plt.tight_layout()
    plt.savefig(save_path, dpi=150, bbox_inches='tight')
    print(f'Training curves saved to: {save_path}')
    
    try:
        plt.show(block=False)
        plt.pause(2)
        plt.close()
    except:
        pass


def compute_class_weights(y: np.ndarray) -> torch.Tensor:
    """
    Compute class weights inversely proportional to class frequencies.
    
    Helps handle imbalanced classes during training.
    
    Args:
        y: Array of class labels
    
    Returns:
        Tensor of weights for each class
    """
    classes, counts = np.unique(y, return_counts=True)
    n_samples = len(y)
    n_classes = len(classes)
    
    weights = n_samples / (n_classes * counts)
    weight_dict = {cls: w for cls, w in zip(classes, weights)}
    
    return torch.tensor([weight_dict[i] for i in range(NUM_CLASSES)],
                        dtype=torch.float32)


# ═══════════════════════════════════════════════════════════
# MAIN TRAINING PIPELINE
# ═══════════════════════════════════════════════════════════

def main():
    """Main training pipeline with 7 stages."""
    print('=' * 65)
    print('  Emotion Pattern Recognition - GRU Training')
    print(f'  Model: {GRUMoodClassifier.__name__}')
    print(f'  Classes: {NUM_CLASSES} complex emotional states')
    print(f'  Method: HSV Histogram Features (17-dim)')
    print(f'  Output dir: {MODELS_DIR}')
    print('=' * 65)
    
    # Set random seeds for reproducibility
    np.random.seed(CONFIG['random_seed'])
    torch.manual_seed(CONFIG['random_seed'])
    
    # ═══ Stage 1: Load Data ═══
    data_path = CONFIG['data_file']
    if not os.path.exists(data_path):
        print(f'[ERROR] Data file not found: {data_path}')
        print('Please run generate_dataset.py first.')
        sys.exit(1)
    
    print(f'\n[1/7] Loading data: {data_path}')
    df = pd.read_csv(data_path)
    print(f'      Records loaded: {len(df)}')
    
    # Verify required columns exist
    missing_cols = [c for c in CONFIG['feature_cols'] if c not in df.columns]
    if missing_cols:
        print(f'[ERROR] Missing feature columns: {missing_cols}')
        sys.exit(1)
    
    if CONFIG['label_col'] not in df.columns:
        print(f'[ERROR] Missing label column: {CONFIG["label_col"]}')
        sys.exit(1)
    
    # ═══ Stage 2: Build Sequences ═══
    print('[2/7] Building sliding window sequences ...')
    X_raw, y_raw = build_sequences(df, CONFIG['window_size'], CONFIG['window_stride'])
    print(f'      Sequences: {len(X_raw)}')
    print(f'      Each sample shape: ({CONFIG["window_size"]}, {CONFIG["input_dim"]})')
    
    # Check class distribution
    unique, counts = np.unique(y_raw, return_counts=True)
    print(f'      Class distribution in raw sequences:')
    for cls_id, cnt in zip(unique, counts):
        name = EMOTION_COLOR_PROFILES[int(cls_id)]['name']
        print(f'        [{int(cls_id):2d}] {name:25s}: {cnt:5d}')
    
    # ═══ Stage 3: Train/Val/Test Split ═══
    print('[3/7] Splitting train/val/test sets ...')
    
    # First split: train+val vs test
    X_temp, X_test, y_temp, y_test = train_test_split(
        X_raw, y_raw,
        test_size=CONFIG['test_split'],
        random_state=CONFIG['random_seed'],
        stratify=y_raw
    )
    
    # Second split: train vs val (from temp)
    val_ratio = CONFIG['validation_split'] / (1 - CONFIG['test_split'])
    X_train, X_val, y_train, y_val = train_test_split(
        X_temp, y_temp,
        test_size=val_ratio,
        random_state=CONFIG['random_seed'],
        stratify=y_temp
    )
    
    print(f'      Train: {len(X_train):6d}')
    print(f'      Val:   {len(X_val):6d}')
    print(f'      Test:  {len(X_test):6d}')
    
    # ═══ Stage 4: Normalize ═══
    print('[4/7] Normalizing features ...')
    scaler = StandardScaler()
    
    # Fit on training data only
    X_train_flat = X_train.reshape(-1, CONFIG['input_dim'])
    scaler.fit(X_train_flat)
    
    # Transform all splits
    X_train_norm = scaler.transform(X_train_flat).reshape(X_train.shape)
    X_val_norm = scaler.transform(X_val.reshape(-1, CONFIG['input_dim'])).reshape(X_val.shape)
    X_test_norm = scaler.transform(X_test.reshape(-1, CONFIG['input_dim'])).reshape(X_test.shape)
    
    # Save scaler
    with open(CONFIG['scaler_out'], 'wb') as f:
        pickle.dump(scaler, f)
    print(f'      Scaler saved: {CONFIG["scaler_out"]}')
    
    # ═══ Stage 5: Prepare DataLoaders ═══
    print('[5/7] Preparing DataLoaders ...')
    
    X_train_t = torch.tensor(X_train_norm, dtype=torch.float32)
    y_train_t = torch.tensor(y_train, dtype=torch.long)
    X_val_t = torch.tensor(X_val_norm, dtype=torch.float32)
    y_val_t = torch.tensor(y_val, dtype=torch.long)
    X_test_t = torch.tensor(X_test_norm, dtype=torch.float32)
    y_test_t = torch.tensor(y_test, dtype=torch.long)
    
    train_loader = DataLoader(
        TensorDataset(X_train_t, y_train_t),
        batch_size=CONFIG['batch_size'],
        shuffle=True,
        num_workers=0
    )
    val_loader = DataLoader(
        TensorDataset(X_val_t, y_val_t),
        batch_size=CONFIG['batch_size'],
        shuffle=False,
        num_workers=0
    )
    test_loader = DataLoader(
        TensorDataset(X_test_t, y_test_t),
        batch_size=CONFIG['batch_size'],
        shuffle=False,
        num_workers=0
    )
    
    # Compute class weights for imbalanced handling
    class_weights = compute_class_weights(y_train)
    print(f'      Class weights computed')
    
    # ═══ Stage 6: Initialize Model ═══
    print('[6/7] Initializing model ...')
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    print(f'      Device: {device}')
    
    # Create model with updated parameters for 16 classes
    model = GRUMoodClassifier(
        input_dim=CONFIG['input_dim'],
        hidden_dim=CONFIG['hidden_dim'],
        num_layers=CONFIG['num_layers'],
        dropout=CONFIG['dropout'],
        num_classes=CONFIG['num_classes']
    ).to(device)
    
    total_params = sum(p.numel() for p in model.parameters())
    trainable_params = sum(p.numel() for p in model.parameters() if p.requires_grad)
    print(f'      Total parameters: {total_params:,}')
    print(f'      Trainable parameters: {trainable_params:,}')
    
    # Loss function with class weights
    criterion = nn.CrossEntropyLoss(weight=class_weights.to(device))
    
    # Optimizer with weight decay
    optimizer = optim.Adam(
        model.parameters(),
        lr=CONFIG['learning_rate'],
        weight_decay=CONFIG['weight_decay']
    )
    
    # Learning rate scheduler
    scheduler = optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode='min', factor=0.5, patience=10, 
    )
    
    # ═══ Stage 7: Training Loop ═══
    print('[7/7] Starting training ...')
    print(f'      Epochs: {CONFIG["epochs"]}')
    print(f'      Batch size: {CONFIG["batch_size"]}')
    print(f'      Learning rate: {CONFIG["learning_rate"]}')
    print(f'      Weight decay: {CONFIG["weight_decay"]}')
    print('-' * 65)
    
    train_loss_history = []
    val_loss_history = []
    train_acc_history = []
    val_acc_history = []
    
    best_val_acc = 0.0
    best_epoch = 0
    patience_counter = 0
    early_stop_patience = 20
    
    epoch_pbar = tqdm(range(1, CONFIG['epochs'] + 1), desc='Training', unit='epoch')
    
    for epoch in epoch_pbar:
        # ---- Training Phase ----
        model.train()
        train_loss = 0.0
        train_correct = 0
        train_total = 0
        
        for batch_X, batch_y in train_loader:
            batch_X, batch_y = batch_X.to(device), batch_y.to(device)
            
            optimizer.zero_grad()
            outputs = model(batch_X)
            loss = criterion(outputs, batch_y)
            loss.backward()
            
            # Gradient clipping to prevent exploding gradients
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            
            optimizer.step()
            
            train_loss += loss.item() * batch_X.size(0)
            _, predicted = torch.max(outputs, 1)
            train_total += batch_y.size(0)
            train_correct += (predicted == batch_y).sum().item()
        
        avg_train_loss = train_loss / len(train_loader.dataset)
        train_acc = train_correct / train_total
        train_loss_history.append(avg_train_loss)
        train_acc_history.append(train_acc)
        
        # ---- Validation Phase ----
        model.eval()
        val_loss = 0.0
        val_correct = 0
        val_total = 0
        
        with torch.no_grad():
            for batch_X, batch_y in val_loader:
                batch_X, batch_y = batch_X.to(device), batch_y.to(device)
                outputs = model(batch_X)
                loss = criterion(outputs, batch_y)
                
                val_loss += loss.item() * batch_X.size(0)
                _, predicted = torch.max(outputs, 1)
                val_total += batch_y.size(0)
                val_correct += (predicted == batch_y).sum().item()
        
        avg_val_loss = val_loss / len(val_loader.dataset)
        val_acc = val_correct / val_total
        val_loss_history.append(avg_val_loss)
        val_acc_history.append(val_acc)
        
        # Update learning rate scheduler
        scheduler.step(avg_val_loss)
        
        # Save best model
        if val_acc > best_val_acc:
            best_val_acc = val_acc
            best_epoch = epoch
            torch.save(model.state_dict(), CONFIG['model_out'])
            patience_counter = 0
        else:
            patience_counter += 1
        
        # Update progress bar
        epoch_pbar.set_postfix({
            'loss': f'{avg_train_loss:.4f}',
            'val_loss': f'{avg_val_loss:.4f}',
            'acc': f'{train_acc:.4f}',
            'val_acc': f'{val_acc:.4f}',
            'best': f'{best_val_acc:.4f}'
        })
        
        # Early stopping
        if patience_counter >= early_stop_patience:
            print(f'\n      Early stopping triggered at epoch {epoch}')
            break
    
    epoch_pbar.close()
    
    # ═══ Final Evaluation ═══
    print('\n' + '-' * 65)
    print(f'Training complete!')
    print(f'Best validation accuracy: {best_val_acc:.4f} at epoch {best_epoch}')
    
    # Load best model for test evaluation
    model.load_state_dict(torch.load(CONFIG['model_out']))
    model.eval()
    
    test_correct = 0
    test_total = 0
    confusion_matrix = np.zeros((NUM_CLASSES, NUM_CLASSES), dtype=int)
    
    with torch.no_grad():
        for batch_X, batch_y in test_loader:
            batch_X, batch_y = batch_X.to(device), batch_y.to(device)
            outputs = model(batch_X)
            _, predicted = torch.max(outputs, 1)
            test_total += batch_y.size(0)
            test_correct += (predicted == batch_y).sum().item()
            
            # Update confusion matrix
            for true, pred in zip(batch_y.cpu().numpy(), predicted.cpu().numpy()):
                confusion_matrix[true, pred] += 1
    
    test_acc = test_correct / test_total
    print(f'Test accuracy: {test_acc:.4f}')
    
    # Per-class accuracy
    print(f'\nPer-class accuracy:')
    print(f'  {"ID":>3s} {"Name":25s} {"Accuracy":>10s} {"Samples":>8s}')
    print(f'  {"-"*3} {"-"*25} {"-"*10} {"-"*8}')
    for cls_id in range(NUM_CLASSES):
        total_cls = confusion_matrix[cls_id].sum()
        correct_cls = confusion_matrix[cls_id, cls_id]
        acc_cls = correct_cls / total_cls if total_cls > 0 else 0
        name = EMOTION_COLOR_PROFILES[cls_id]['name']
        print(f'  {cls_id:3d} {name:25s} {acc_cls:10.4f} {total_cls:8d}')
    
    # Save model info
    print(f'\nModel saved: {CONFIG["model_out"]}')
    print(f'Scaler saved: {CONFIG["scaler_out"]}')
    
    # Plot curves
    print('\nGenerating training curves ...')
    plot_training_curves(
        train_loss_history, val_loss_history,
        train_acc_history, val_acc_history,
        CONFIG['plot_out']
    )
    
    print('=' * 65)
    print('Training completed successfully!')


if __name__ == '__main__':
    main()