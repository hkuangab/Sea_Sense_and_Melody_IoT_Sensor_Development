# ============================================
# 导入matplotlib库用于绘图，numpy库用于数值计算
# ============================================
import matplotlib.pyplot as plt
import numpy as np

# ============================================
# 生成数据
# ============================================
# 创建从0到2π的数组，步长为0.1
# arange(start, stop, step) 生成等差数列
x = np.arange(0, 2 * np.pi, .1)

# 计算正弦值
y = np.sin(x)

# 计算余弦值
y2 = np.cos(x)

# 计算二次函数值 (x² + 4)
y3 = np.square(x) + 4

# ============================================
# 设置图表样式
# ============================================
# 显示网格线
plt.grid(True)

# 设置X轴标签
plt.xlabel('My X Values')

# 设置Y轴标签
plt.ylabel('My Y Values')

# 设置图表标题
plt.title('My First Graph')

# ============================================
# 注释掉的代码说明
# ============================================
# plt.axis([0,5,2,11])  # 这行被注释了
# 作用：手动设置坐标轴范围 [xmin, xmax, ymin, ymax]

# ============================================
# 绘制曲线
# ============================================

# 绘制正弦曲线
# 'b-^' 表示：蓝色(b) 实线(-) 三角形标记(^)
# linewidth=3  线条粗细为3
# markersize=7 标记点大小为7
# label       图例名称
plt.plot(x, y, 'b-^', linewidth=3, markersize=7, label='Sin(x)')

# 绘制余弦曲线
# 'r-^' 表示：红色(r) 实线(-) 三角形标记(^)
plt.plot(x, y2, 'r-^', linewidth=3, markersize=7, label='Cos(x)')

# ============================================
# 注释掉的代码说明
# ============================================
# plt.plot(x,y3,'g-^',linewidth=3,markersize=7,label='Green Line')
# 这行被注释了
# 作用：绘制绿色(g)的二次函数曲线

# ============================================
# 显示图例
# ============================================
# loc='upper center' 将图例放在图表上方中央位置
plt.legend(loc='upper center')

# ============================================
# 显示图表
# ============================================
plt.show()