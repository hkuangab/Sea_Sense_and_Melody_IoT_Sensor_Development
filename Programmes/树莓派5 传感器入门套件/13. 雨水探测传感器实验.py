# -*- coding: utf-8 -*-
"""
Raspberry Pi 雨滴检测和电位器读取程序
使用GPIO库：gpiozero
功能：检测雨滴传感器状态并读取电位器模拟值
"""

# 1. 导入必要的库
from gpiozero import Button, MCP3008
from signal import pause
from time import sleep

# ============================================================================
# 硬件初始化部分
# ============================================================================

# 2. 定义使用通道和雨滴传感器数字量IO口
# 初始化雨滴传感器数字输出引脚（GPIO 17）
# 当传感器检测到雨滴时，引脚为低电平（0），否则为高电平（1）
makerobo_DO = Button(17) # 雨滴传感器的数字管脚

# 初始化MCP3008模数转换器的通道0
# 用于读取电位器的模拟值，范围0-1对应0-3.3V
pot = MCP3008(channel=0)

# ============================================================================
# 3. 初始化工作以及中断函数定义
# ============================================================================

def pressed():
    """当雨滴传感器检测到雨滴时（按钮按下）调用的函数"""
    print("Raining!")

def released():
    """当雨滴传感器不再检测到雨滴时（按钮释放）调用的函数"""
    print("Not Raining!")

# 设置雨滴传感器事件回调
makerobo_DO.when_pressed = pressed
makerobo_DO.when_released = released

# ============================================================================
# 工具函数
# ============================================================================

# 4. 循环函数
def MAP(x, in_min, in_max, out_min, out_max):
    """
    线性映射函数
    将输入值x从输入范围[in_min, in_max]映射到输出范围[out_min, out_max]
    
    参数：
    x: 要映射的输入值
    in_min: 输入范围最小值
    in_max: 输入范围最大值
    out_min: 输出范围最小值
    out_max: 输出范围最大值
    
    返回：
    映射后的值
    """
    return (x - in_min) * (out_max - out_min) / (in_max - in_min) + out_min

# ============================================================================
# 主循环函数
# ============================================================================

def makerobo_loop():
    """
    主循环函数
    持续读取电位器值，将其映射到0-100范围，并打印原始值
    """
    while True:
        # 读取电位器原始值（0-1之间）
        pot_value = pot.value
        
        # 将原始值（0-1）映射到0-100范围
        mapped_value = MAP(pot_value, 0, 1, 0, 100)
        
        # 打印原始电位器值，保留两位小数
        print("Raw potentiometer value: {:.2f}".format(pot_value))
        print("Mapped value: {:.2f}".format(mapped_value))
        
        # 等待0.2秒，避免过快读取
        sleep(0.2)

# ============================================================================
# 5. 主程序入口
# ============================================================================

if __name__ == "__main__":
    try:
        # 启动主循环
        makerobo_loop()
    except KeyboardInterrupt:
        # 当用户按下Ctrl+C时，清理资源并退出程序
        print("\nProgram stopped by user")
        makerobo_DO.close()
        print("GPIO resources released")